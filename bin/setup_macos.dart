/// Prepare native CEF artifacts and local Xcode settings for a consuming app.
library;

import 'dart:convert';
import 'dart:io';

Future<void> main() async {
  if (!Platform.isMacOS) {
    stderr.writeln('CEF macOS setup must run on macOS.');
    exitCode = 1;
    return;
  }
  final config = File('.dart_tool/package_config.json');
  final flutterDirectory = Directory('macos/Flutter');
  if (!config.existsSync() || !flutterDirectory.existsSync()) {
    stderr.writeln(
        'Run flutter pub get, then run this command from your Flutter app directory.');
    exitCode = 1;
    return;
  }
  final packages = (jsonDecode(config.readAsStringSync())
      as Map<String, dynamic>)['packages'] as List<dynamic>;
  final package = packages
      .cast<Map<String, dynamic>>()
      .singleWhere((p) => p['name'] == 'webview_cef');
  final root = Directory.fromUri(
          config.absolute.uri.resolve(package['rootUri'] as String))
      .resolveSymbolicLinksSync();
  final macos = '$root/macos';
  final process = await Process.start(
      'bash', ['$macos/scripts/download_cef.sh'],
      mode: ProcessStartMode.inheritStdio);
  final result = await process.exitCode;
  if (result != 0) {
    exitCode = result;
    return;
  }
  final arch = (await Process.run('uname', ['-m'])).stdout.toString().trim();
  File('${flutterDirectory.path}/webview_cef.xcconfig').writeAsStringSync(
      '''// Generated by dart run webview_cef:setup_macos. Do not commit.
WEBVIEW_CEF_MACOS_DIR = $macos
ARCHS = $arch
ONLY_ACTIVE_ARCH = YES
MACOSX_DEPLOYMENT_TARGET = 12.0
ENABLE_USER_SCRIPT_SANDBOXING = NO
''');
  stdout.writeln(
      'CEF prepared. Include Flutter/webview_cef.xcconfig in your Runner configurations and add the Embed CEF build phase (see README).');
}
